export type FeQuizChoiceId = "ア" | "イ" | "ウ" | "エ";

export interface FeQuizChoice {
  id: FeQuizChoiceId;
  text: string;
}

export interface FeQuizMeta {
  slug: string;
  order: number;
  /** 関連する構文別レッスン */
  lesson: FeLessonSlug;
  /** trace = 出力を答える / fill = 空欄に入る記述を選ぶ */
  kind: "trace" | "fill";
  /**
   * basic = レッスンを読めば解ける基礎 / exam = 本番の科目 B 相当。
   * 一覧で 2 層に分けて「どこから難化するか」を見せるために持つ。
   */
  tier: "basic" | "exam";
  title: string;
  shortTitle: string;
  description: string;
  keywords: string[];
  prompt: string;
  /** 一覧カード用の 1 行要約。答えを明かさずに「何をするコードか」だけ書く */
  challenge: string;
  code: string;
  choices: FeQuizChoice[];
  answer: FeQuizChoiceId;
  explanation: string[];
  /** 誤答を誘う仕掛けの正体。1 行で言い切る */
  trap: string;
  /** fill 問題で空欄を正解で埋めた完成コード (trace では省略) */
  verifyCode?: string;
  /** 実行したときの出力 (改行区切り) */
  expectedOutput: string;
}

